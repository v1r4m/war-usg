"""
Real-S3 mode for the "Deleted, Not Gone" lab.

When S3_LAB_BUCKET is set, the challenge links to that bucket's website endpoint and the
in-memory routes are turned off. The wargame never writes to AWS, so it needs no access key:
`flask s3-script` prints a shell script that you paste into AWS CloudShell, which runs with
your console login.

Set S3_LAB_FLAG as well to pin the flag, so `flask reset-flags` can't drift away from what
is in the bucket.

The bucket itself is created once by hand (versioning on, static website hosting on,
public policy allowing only s3:Get* on objects and s3:ListBucketVersions).
"""
import os
import secrets

from .labs import s3_lab_objects, s3_mime

LAB_KEY = "s3versions"


def bucket_name():
    return os.environ.get("S3_LAB_BUCKET") or None


def fixed_flag():
    return (os.environ.get("S3_LAB_FLAG") or "").strip() or None


def region():
    return os.environ.get("S3_LAB_REGION") or "ap-northeast-2"


def website_url(bucket=None):
    return f"http://{bucket or bucket_name()}.s3-website.{region()}.amazonaws.com/"


def rest_url(bucket=None):
    return f"https://{bucket or bucket_name()}.s3.{region()}.amazonaws.com"


def cloudshell_script(flag, bucket=None, purge_only=False):
    """A bash script that empties the bucket (every version and delete marker, so old flags
    don't linger) and uploads every version in order. A None body becomes a delete marker."""
    bucket = bucket or bucket_name()
    lines = [
        "#!/usr/bin/env bash",
        "# Paste into AWS CloudShell. Generated by `flask s3-script`.",
        "set -euo pipefail",
        f"B={bucket}",
        f"R={region()}",
        "",
        'echo "Emptying s3://$B (all versions and delete markers) ..."',
        "aws s3api list-object-versions --bucket \"$B\" --region \"$R\" --output text \\",
        "  --query '[Versions, DeleteMarkers][][].[Key, VersionId]' |",
        "while IFS=$'\\t' read -r key vid; do",
        '  [ -z "$key" ] || [ "$key" = "None" ] && continue',
        '  aws s3api delete-object --bucket "$B" --region "$R" --key "$key" --version-id "$vid" > /dev/null',
        "done",
    ]
    if purge_only:
        lines.append('echo "Done. s3://$B is empty."')
        return "\n".join(lines) + "\n"

    lines += ["", 'W=$(mktemp -d)', 'echo "Uploading ..."']
    objects = s3_lab_objects(flag, rest_base=rest_url(bucket), web_base="", back_link=None)
    for key, versions in objects.items():
        for body in (v[1] for v in versions):
            if body is None:
                lines.append(f'aws s3api delete-object --bucket "$B" --region "$R" --key "{key}" > /dev/null')
                continue
            tag = f"USG_EOF_{secrets.token_hex(4)}"
            lines += [
                f"cat > \"$W/body\" <<'{tag}'",
                body,
                tag,
                f'aws s3api put-object --bucket "$B" --region "$R" --key "{key}" '
                f'--content-type "{s3_mime(key)}" --body "$W/body" > /dev/null',
            ]
    lines += [
        'rm -rf "$W"',
        f'echo "Done. Website: {website_url(bucket)}"',
    ]
    return "\n".join(lines) + "\n"
